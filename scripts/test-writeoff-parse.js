const { extractWriteOffAmountFromText } = require('../src/moneySources');

const samples = [
  ['Цена: 100\nСумма: 1 250', [], 1250],
  ['цена 99.5', [], null],
  ['Всего к списанию: 3400', [], 3400],
  ['на сумму 500.50', [], 500.5],
  ['Цена 200 Сумма 900', [], 900],
  ['Итого цена 50', [], null],
  ['сумма 297.99', [], 297.99],
  ['всего 10 000', [], 10000],
  ['Товар А цена 15\nТовар Б цена 20\nвсего 35', [], 35],
  ['Списание\nсумма 48600\nвсего по складу 3329', [3329], 3329],
  ['сумма 48600', [3329], null],
  ['сумма 3 329\nостаток 48600', [3329], 3329],
  ['сумма 87\nвсего 595.98', [87, 595.98], 595.98],
  ['сумма 595.98', [87, 595.98], 595.98],
  // в превью только эквайринг 87 — не считать списанием, пусть откроют задачу
  ['Списание со склада Нал-Ю26-2900\n87', [87, 595.98], null],
  ['Списание со склада\nсумма 3329', [3329], 3329],
  // пробел в тысячах
  ['сумма 3 000', [], 3000],
  ['Цена: 3 329\nКол-во: 1', [3329], 3329],
  // 1 шт: цена = сумма
  ['Цена: 595,98\nКоличество: 1', [87, 595.98], 595.98],
  ['Товар X\nСтоимость 595.98\n1 шт', [87, 595.98], 595.98],
  ['цена 3 329', [3329], 3329],
  // описание без слова «списание», графа есть у цены
  ['Кабель\nЦена: 595,98', [87, 595.98], 595.98],
];

let fail = 0;
for (const [t, prefers, expect] of samples) {
  const got = extractWriteOffAmountFromText(t, prefers);
  const ok = Object.is(got, expect) || got === expect;
  if (!ok) fail++;
  console.log(ok ? 'OK  ' : 'FAIL', JSON.stringify(t), 'pref', prefers, '=>', got, 'want', expect);
}
process.exit(fail ? 1 : 0);
